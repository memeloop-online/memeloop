import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const outDir = path.join(process.cwd(), 'src/llm/providers');

await mkdir(outDir, { recursive: true });

const providers = [
  { id: 'openai',        pkg: '@ai-sdk/openai',       createFn: 'createOpenAI',           defaultBase: 'https://api.openai.com/v1' },
  { id: 'anthropic',     pkg: '@ai-sdk/anthropic',    createFn: 'createAnthropic',        defaultBase: 'https://api.anthropic.com/v1' },
  { id: 'google',        pkg: '@ai-sdk/google',       createFn: 'createGoogleGenerativeAI', defaultBase: 'https://generativelanguage.googleapis.com/v1beta' },
  { id: 'deepseek',      pkg: '@ai-sdk/deepseek',     createFn: 'createDeepSeek',         defaultBase: 'https://api.deepseek.com/v1' },
  { id: 'groq',          pkg: '@ai-sdk/groq',         createFn: 'createGroq',             defaultBase: 'https://api.groq.com/openai/v1' },
  { id: 'mistral',       pkg: '@ai-sdk/mistral',      createFn: 'createMistral',          defaultBase: 'https://api.mistral.ai/v1' },
  { id: 'cohere',        pkg: '@ai-sdk/cohere',       createFn: 'createCohere',           defaultBase: 'https://api.cohere.com/v1' },
  { id: 'xai',           pkg: '@ai-sdk/xai',          createFn: 'createXai',              defaultBase: 'https://api.x.ai/v1' },
  { id: 'togetherai',    pkg: '@ai-sdk/togetherai',   createFn: 'createTogetherAI',       defaultBase: 'https://api.together.xyz/v1' },
  { id: 'perplexity',    pkg: '@ai-sdk/perplexity',   createFn: 'createPerplexity',       defaultBase: 'https://api.perplexity.ai' },
  { id: 'azure',         pkg: '@ai-sdk/azure',        createFn: 'createAzure',            defaultBase: null },
  { id: 'google-vertex', pkg: '@ai-sdk/google-vertex', createFn: 'createVertex',          defaultBase: null },
];

const barrelExports = [];

for (const { id, pkg, createFn, defaultBase } of providers) {
  const hasDefaultBase = defaultBase !== null;
  const interfaceName = id.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join('') + 'ProviderConfig';
  const factoryName = 'create' + id.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join('') + 'Provider';

  const baseConfig = hasDefaultBase
    ? `  /** Override the default API base URL. */\n  baseUrl?: string;\n  /** API key. */\n  apiKey?: string;`
    : `  /** API key or credential. */\n  apiKey?: string;\n  /** Additional provider-specific options. See @ai-sdk/${id} docs. */\n  options?: Record<string, unknown>;`;

  const sdkArgs = hasDefaultBase
    ? `baseURL: config.baseUrl ?? '${defaultBase}',\n    apiKey: config.apiKey,`
    : `apiKey: config.apiKey,\n    ...config.options,`;

  const content = `/**
 * Pre-built ${id.toUpperCase()} provider — wraps @ai-sdk/${id.split('/').pop()}.
 *
 * Import from 'memeloop/${id}' (bundles only @ai-sdk/${id.split('/').pop()}).
 * Or inject your own via createFetchLLMProvider from 'memeloop'.
 */
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — provider package may be at a different AI SDK version than core
import { ${createFn} } from '${pkg}';
import { createFetchLLMProvider, type FetchLLMProviderConfig } from '../fetchProvider.js';
import type { ILLMProvider } from '../../types.js';

// ─── Config ────────────────────────────────────────────────────────────

export interface ${interfaceName} extends Omit<FetchLLMProviderConfig, 'createModel'> {
${baseConfig}
}

// ─── Factory ───────────────────────────────────────────────────────────

/**
 * Create an ILLMProvider backed by ${id.toUpperCase()}.
 *
 * @example
 * \`\`\`ts
 * import { ${factoryName} } from 'memeloop/${id}';
 * const provider = ${factoryName}({ name: 'my-${id}', apiKey: '...' });
 * \`\`\`
 */
export function ${factoryName}(config: ${interfaceName}): ILLMProvider {
  const sdk = ${createFn}({
    ${sdkArgs}
  });
  return createFetchLLMProvider({
    name: config.name,
    // Provider packages may return LanguageModelV1..V4 — cast to satisfy core types
    createModel: (modelId: string) => sdk(modelId) as any,
  });
}
`;

  const filePath = path.join(outDir, `${id}.ts`);
  await writeFile(filePath, content);

  barrelExports.push(`export { ${factoryName}, type ${interfaceName} } from './${id}.js';`);

  console.log(`✅ ${id}.ts`);
}

// Write barrel
await writeFile(
  path.join(outDir, 'index.ts'),
  `// Generated by scripts/generate-provider-wrappers.mjs.
// Pre-built provider wrappers for Vercel AI SDK.

${barrelExports.join('\n')}
`
);

console.log(`✅ index.ts (${providers.length} providers)`);
