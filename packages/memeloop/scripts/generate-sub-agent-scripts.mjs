import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const packageRoot = process.cwd();

const scriptGroups = [
  {
    loopId: 'sub-agent',
    scriptsDir: path.join(packageRoot, 'src/agentLoops/sub-agent/scripts'),
    mapName: 'builtinSubAgentScriptSources',
    getterName: 'getBuiltinSubAgentScriptSource',
  },
  {
    loopId: 'llm-io',
    scriptsDir: path.join(packageRoot, 'src/agentLoops/llm-io/scripts'),
    mapName: 'builtinLlmIoScriptSources',
    getterName: 'getBuiltinLlmIoScriptSource',
  },
];

function toScriptId(loopId, fileName) {
  return `builtin:${loopId}/${fileName.replace(/\.mjs$/, '')}`;
}

function toConstName(scriptId) {
  return `${scriptId
    .replace(/^builtin:/, '')
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, char) => String(char).toUpperCase())
    .replace(/^[a-z]/, char => char.toUpperCase())}ScriptId`;
}

function toAliasName(scriptId) {
  return `BUILTIN_${scriptId.replace(/^builtin:/, '').replace(/[^a-zA-Z0-9]+/g, '_').toUpperCase()}_SCRIPT_ID`;
}

function quote(value) {
  if (value.includes("'") && !value.includes('"')) {
    return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
  }
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function sourceExpression(source) {
  const chunks = source.split('\n');
  return `[
${chunks.map(chunk => `    ${quote(chunk)}`).join(',\n')},
  ].join('\\n')`;
}

for (const group of scriptGroups) {
  const files = (await readdir(group.scriptsDir))
    .filter(fileName => fileName.endsWith('.mjs'))
    .sort();

  const entries = [];
  for (const fileName of files) {
    const source = await readFile(path.join(group.scriptsDir, fileName), 'utf8');
    const scriptId = toScriptId(group.loopId, fileName);
    entries.push({ constName: toConstName(scriptId), aliasName: toAliasName(scriptId), scriptId, source });
  }

  const lines = [
    '// Generated by scripts/generate-sub-agent-scripts.mjs. Edit the sibling .mjs files instead.',
    '',
  ];

  for (const entry of entries) {
    lines.push(`export const ${entry.constName} = ${quote(entry.scriptId)};`);
  }

  lines.push('');
  for (const entry of entries) {
    lines.push(`export const ${entry.aliasName} = ${entry.constName};`);
  }

  lines.push('', `export const ${group.mapName}: Readonly<Record<string, string>> = {`);

  for (const entry of entries) {
    lines.push(`  [${entry.constName}]: ${sourceExpression(entry.source)},`);
  }

  lines.push(
    '};',
    '',
    `export function ${group.getterName}(id: string): string | undefined {`,
    `  return ${group.mapName}[id];`,
    '}',
    '',
  );

  const outputFile = path.join(group.scriptsDir, 'builtinScripts.ts');
  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, lines.join('\n'));
}