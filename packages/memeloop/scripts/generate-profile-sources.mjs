/**
 * Generate builtinProfileSources.ts from src/loopProfiles/*.json.
 *
 * Embeds each profile JSON as a string constant so no runtime fs/path is needed.
 * Same pattern as generate-loop-sources.mjs for .mjs loop scripts.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const packageRoot = process.cwd();
const profilesDir = path.join(packageRoot, 'src/loopProfiles');
const outFile = path.join(packageRoot, 'src/loopProfiles/builtinProfileSources.ts');

const jsonFiles = (await readdir(profilesDir))
  .filter((f) => f.endsWith('.json'))
  .sort();

function quote(value) {
  if (value.includes("'") && !value.includes('"')) {
    return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
  }
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function sourceExpression(source) {
  const chunks = source.split('\n');
  return `[\n${chunks.map((chunk) => `    ${quote(chunk)}`).join(',\n')},\n  ].join('\\n')`;
}

function toProfileId(fileName) {
  return fileName.replace(/\.json$/, '');
}

const entries = [];
for (const fileName of jsonFiles) {
  const source = await readFile(path.join(profilesDir, fileName), 'utf8');
  // Validate JSON
  JSON.parse(source);
  entries.push({ id: toProfileId(fileName), source });
}

const lines = [
  '// Generated by scripts/generate-profile-sources.mjs. Edit src/loopProfiles/*.json instead.',
  '',
  '/** Builtin Loop Profile JSON sources, embedded at build time. */',
  'export const builtinProfileSources: Readonly<Record<string, string>> = {',
];

for (const entry of entries) {
  lines.push(`  ${quote(entry.id)}: ${sourceExpression(entry.source)},`);
}

lines.push('};');
lines.push('');

await writeFile(outFile, lines.join('\n') + '\n');
console.log(`✅ Generated ${outFile} with ${entries.length} profiles: ${entries.map((e) => e.id).join(', ')}`);
