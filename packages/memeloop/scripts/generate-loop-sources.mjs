import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const packageRoot = process.cwd();

const scriptGroups = [
  {
    loopId: 'agent-agent-loop',
    scriptsDir: path.join(packageRoot, 'src/loops/agent-agent-loop'),
    mapName: 'builtinAgentAgentLoopSources',
    getterName: 'getBuiltinAgentAgentLoopSource',
    moduleMapName: 'builtinAgentAgentLoopModules',
    moduleGetterName: 'getBuiltinAgentAgentLoopModule',
  },
  {
    loopId: 'agent-tool-loop',
    scriptsDir: path.join(packageRoot, 'src/loops/agent-tool-loop'),
    mapName: 'builtinAgentToolLoopSources',
    getterName: 'getBuiltinAgentToolLoopSource',
    moduleMapName: 'builtinAgentToolLoopModules',
    moduleGetterName: 'getBuiltinAgentToolLoopModule',
  },
];

function toScriptId(loopId, fileName) {
  return `builtin:${loopId}/${fileName.replace(/\.mjs$/, '')}`;
}

function toConstName(scriptId) {
  return `${scriptId
    .replace(/^builtin:/, '')
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, char) => String(char).toUpperCase())
    .replace(/^[a-z]/, char => char.toUpperCase())}ScriptId`;
}

function toAliasName(scriptId) {
  return `BUILTIN_${scriptId.replace(/^builtin:/, '').replace(/[^a-zA-Z0-9]+/g, '_').toUpperCase()}_SCRIPT_ID`;
}

function toImportName(fileName) {
  const name = fileName
    .replace(/\.mjs$/, '')
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, char) => String(char).toUpperCase())
    .replace(/^[A-Z]/, char => char.toLowerCase());
  return `builtin${name[0].toUpperCase()}${name.slice(1)}`;
}

function quote(value) {
  if (value.includes("'") && !value.includes('"')) {
    return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
  }
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function sourceExpression(source) {
  const chunks = source.split('\n');
  return `[
${chunks.map(chunk => `    ${quote(chunk)}`).join(',\n')},
  ].join('\\n')`;
}

for (const group of scriptGroups) {
  const files = (await readdir(group.scriptsDir))
    .filter(fileName => fileName.endsWith('.mjs'))
    .sort();

  const entries = [];
  for (const fileName of files) {
    const source = await readFile(path.join(group.scriptsDir, fileName), 'utf8');
    const scriptId = toScriptId(group.loopId, fileName);
    entries.push({
      constName: toConstName(scriptId),
      aliasName: toAliasName(scriptId),
      fileName,
      importName: toImportName(fileName),
      scriptId,
      source,
    });
  }

  const lines = [
    '// Generated by scripts/generate-loop-sources.mjs. Edit the sibling .mjs files instead.',
    '',
  ];

  for (const entry of entries) {
    lines.push(`export const ${entry.constName} = ${quote(entry.scriptId)};`);
  }

  lines.push('');
  for (const entry of entries) {
    lines.push(`export const ${entry.aliasName} = ${entry.constName};`);
  }

  lines.push('', `export const ${group.mapName}: Readonly<Record<string, string>> = {`);

  for (const entry of entries) {
    lines.push(`  [${entry.constName}]: ${sourceExpression(entry.source)},`);
  }

  lines.push(
    '};',
    '',
    `export function ${group.getterName}(id: string): string | undefined {`,
    `  return ${group.mapName}[id];`,
    '}',
    '',
  );

  const outputFile = path.join(group.scriptsDir, 'builtinLoopSources.ts');
  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, lines.join('\n'));

  const moduleImports = [
    {
      path: './builtinLoopSources.js',
      line: `import { ${entries.map(entry => entry.constName).join(', ')} } from './builtinLoopSources.js';`,
    },
    ...entries.map(entry => ({
      path: `./${entry.fileName}`,
      line: `import ${entry.importName} from './${entry.fileName}';`,
    })),
  ].sort((left, right) => left.path < right.path ? -1 : left.path > right.path ? 1 : 0);
  const moduleLines = [
    '// Generated by scripts/generate-loop-sources.mjs. Edit the sibling .mjs files instead.',
    '',
    ...moduleImports.map(entry => entry.line),
    '',
    `export const ${group.moduleMapName}: Readonly<Record<string, unknown>> = {`,
    ...entries.map(entry => `  [${entry.constName}]: { default: ${entry.importName} },`),
    '};',
    '',
    `export function ${group.moduleGetterName}(id: string): unknown {`,
    `  return ${group.moduleMapName}[id];`,
    '}',
    '',
  ];
  await writeFile(
    path.join(group.scriptsDir, 'builtinLoopModules.ts'),
    moduleLines.join('\n'),
  );
}
